"""Slurm on the emulated cluster: config rendering, start-up, and acceptance checks.

Covers PRD F2 (1/2/4/8-node jobs with explicit CPU, RAM and time requests) and the
process side of F3 (limits enforced on the real processes, exit codes propagated,
everything cleaned up on cancellation or timeout). Containerised job steps are a later
increment; these checks run plain processes inside the emulated nodes.
"""

from __future__ import annotations

import base64
import re
import secrets
import subprocess
import time
from dataclasses import dataclass, field

from . import emu

PARTITION = "emu"
USER = "dcuser"
USER_UID = 2000  # matches emu/node.Dockerfile
KILL_WAIT_S = 5
SLURMD_RESERVED_MB = 128  # left outside Slurm's RealMemory for slurmd/munged themselves

CGROUP_CONF = """\
CgroupPlugin=cgroup/v2
IgnoreSystemd=yes
ConstrainCores=yes
ConstrainRAMSpace=yes
ConstrainSwapSpace=yes
AllowedSwapSpace=0
"""


def real_memory_mb(container_memory_mb: int) -> int:
    return container_memory_mb - SLURMD_RESERVED_MB


HW_KEYS = ("CPUs", "Boards", "SocketsPerBoard", "CoresPerSocket", "ThreadsPerCore")


def parse_slurmd_c(text: str) -> dict[str, int]:
    """Hardware topology from `slurmd -C`, as slurmd itself will detect it."""
    fields = dict(kv.split("=", 1) for kv in text.split() if "=" in kv)
    return {k: int(fields[k]) for k in HW_KEYS}


def render_slurm_conf(plan: emu.Plan, cores: int, memory_mb: int, hw: dict[str, int]) -> str:
    workers = plan.hosts[1:]
    controller = plan.hosts[0]
    lines = [
        "# Generated by daisychain from the emulated cluster plan. Do not edit by hand.",
        "ClusterName=daisychain",
        f"SlurmctldHost={controller}",
        "SlurmUser=slurm",
        "AuthType=auth/munge",
        "CredType=cred/munge",
        "StateSaveLocation=/var/spool/slurmctld",
        "SlurmdSpoolDir=/var/spool/slurmd",
        "SlurmctldLogFile=/var/log/slurm/slurmctld.log",
        "SlurmdLogFile=/var/log/slurm/slurmd.log",
        "SlurmctldPidFile=/run/slurmctld.pid",
        "SlurmdPidFile=/run/slurmd.pid",
        "ProctrackType=proctrack/cgroup",
        "TaskPlugin=task/cgroup,task/affinity",
        "SelectType=select/cons_tres",
        "SelectTypeParameters=CR_Core_Memory",
        "DefMemPerCPU=128",
        "JobAcctGatherType=jobacct_gather/cgroup",
        "JobCompType=jobcomp/filetxt",
        "JobCompLoc=/var/log/slurm/jobcomp.log",
        "AccountingStorageType=accounting_storage/none",
        "MpiDefault=none",
        "ReturnToService=2",
        f"KillWait={KILL_WAIT_S}",
        "Epilog=/etc/slurm/epilog.sh",
        "MinJobAge=600",
        "SlurmctldTimeout=30",
        "SlurmdTimeout=30",
        "InactiveLimit=0",
        "",
    ]
    topo = " ".join(f"{k}={hw[k]}" for k in HW_KEYS)
    allowed = emu.worker_cpusets(len(workers), cores, hw["CPUs"])
    for w, cpus in zip(workers, allowed):
        spec = sorted(set(range(hw["CPUs"])) - {int(c) for c in cpus.split(",")})
        spec_arg = f" CpuSpecList={','.join(map(str, spec))}" if spec else ""
        lines.append(f"NodeName={w} NodeAddr={plan.addresses[w]} {topo}{spec_arg} "
                     f"RealMemory={real_memory_mb(memory_mb)} State=UNKNOWN")
    lines.append(f"PartitionName={PARTITION} Nodes={','.join(workers)} Default=YES "
                 "MaxTime=60 State=UP")
    return "\n".join(lines) + "\n"


def _put(node: str, path: str, data: bytes) -> None:
    b64 = base64.b64encode(data).decode()
    emu._docker("exec", "-i", emu.container(node), "sh", "-c", f"base64 -d > {path}", input=b64)


def start(plan: emu.Plan, cores: int, memory_mb: int, log=print, timeout_s: int = 90) -> None:
    key = secrets.token_bytes(1024)
    hw = parse_slurmd_c(emu.exec_(plan.hosts[1], "slurmd", "-C").stdout)
    conf = render_slurm_conf(plan, cores, memory_mb, hw).encode()
    for h in plan.hosts:
        _put(h, "/etc/munge/munge.key", key)
        _put(h, "/etc/slurm/slurm.conf", conf)
        _put(h, "/etc/slurm/cgroup.conf", CGROUP_CONF.encode())
    emu.exec_(plan.hosts[0], "/usr/local/sbin/node-init.sh", "controller")
    for w in plan.hosts[1:]:
        emu.exec_(w, "/usr/local/sbin/node-init.sh", "worker")

    deadline = time.monotonic() + timeout_s
    states: dict[str, str] = {}
    while time.monotonic() < deadline:
        states = node_states(plan)
        if states and all(s == "idle" for s in states.values()):
            log(f"slurm: {len(states)} node(s) idle in partition {PARTITION}")
            wait_nfs_ready(plan, log=log)
            return
        time.sleep(2)
    raise emu.EmuError(f"slurm nodes not idle after {timeout_s}s: {states}")


def wait_nfs_ready(plan: emu.Plan, timeout_s: int = 120, log=print) -> None:
    """Block until a worker can open a file on NFS, i.e. the server's grace period is over."""
    t0 = time.monotonic()
    while time.monotonic() - t0 < timeout_s:
        r = emu.exec_(plan.hosts[1], "timeout", "10", "cat", "/shared/.ready", check=False)
        if r.returncode == 0:
            log(f"nfs: /shared readable on {plan.hosts[1]} after {time.monotonic() - t0:.0f}s "
                "(NFSv4 grace period over)")
            return
        time.sleep(2)
    raise emu.EmuError(f"NFS not readable after {timeout_s}s")


def node_states(plan: emu.Plan) -> dict[str, str]:
    r = emu.exec_(plan.hosts[0], "sinfo", "-h", "-N", "-o", "%N %T", check=False)
    if r.returncode != 0:
        return {}
    return dict(line.split() for line in r.stdout.splitlines() if line.strip())


# ---- acceptance checks ------------------------------------------------------------------


@dataclass
class Check:
    name: str
    ok: bool
    detail: str
    data: dict = field(default_factory=dict)


def _as_user(plan: emu.Plan, cmd: str, timeout: int = 120) -> subprocess.CompletedProcess:
    return subprocess.run(
        ["docker", "exec", "-u", USER, "-w", f"/home/{USER}", emu.container(plan.hosts[0]),
         "bash", "-lc", cmd],
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, timeout=timeout)


def _job_field(plan: emu.Plan, job_id: str, key: str) -> str | None:
    r = emu.exec_(plan.hosts[0], "scontrol", "show", "job", job_id, check=False)
    m = re.search(rf"\b{key}=(\S+)", r.stdout)
    return m.group(1) if m else None


def _user_procs(plan: emu.Plan) -> dict[str, list[str]]:
    left = {}
    for w in plan.hosts[1:]:
        r = emu.exec_(w, "pgrep", "-u", USER, "-a", check=False)
        if r.stdout.strip():
            left[w] = r.stdout.strip().splitlines()
    return left


def check_nodes(plan: emu.Plan) -> Check:
    st = node_states(plan)
    ok = len(st) == len(plan.hosts) - 1 and all(s == "idle" for s in st.values())
    return Check("nodes_idle", ok, ", ".join(f"{n}:{s}" for n, s in sorted(st.items())), st)


def check_allocation(plan: emu.Plan, n: int) -> Check:
    r = _as_user(plan, f"srun -N{n} --ntasks-per-node=1 -c1 --mem=64M -t 1 hostname")
    hosts = sorted(r.stdout.split())
    ok = r.returncode == 0 and len(set(hosts)) == n and set(hosts) <= set(plan.hosts[1:])
    return Check(f"alloc_{n}_nodes", ok, " ".join(hosts) or r.stderr.strip()[-200:],
                 {"hosts": hosts})


LIMIT_PROBE = (
    "p=/sys/fs/cgroup$(cut -d: -f3 /proc/self/cgroup); m=max; "
    "while [ \"$p\" != /sys/fs/cgroup ] && [ \"$m\" = max ]; do "
    "m=$(cat $p/memory.max); p=$(dirname $p); done; "
    "echo mem=$m; echo cpus=$(nproc); grep Cpus_allowed_list /proc/self/status"
)


def check_limits(plan: emu.Plan, cores: int, host_cpus: int, launcher: str = "",
                 label: str = "") -> Check:
    """Limits on the real task processes, on the first and last worker.

    The last worker matters: CPU-binding bugs only appear on workers whose CPU share does
    not start at CPU 0.
    """
    workers = plan.hosts[1:]
    allowed = dict(zip(workers, emu.worker_cpusets(len(workers), cores, host_cpus)))
    parts, data, ok = [], {}, True
    for w in dict.fromkeys([workers[0], workers[-1]]):
        r = _as_user(plan, f"srun -w {w} -N1 -n1 -c1 --mem=200M -t 1 "
                           f"{launcher}bash -c '{LIMIT_PROBE}'")
        mem = re.search(r"mem=(\d+)", r.stdout)
        cpus = re.search(r"cpus=(\d+)", r.stdout)
        bound = re.search(r"Cpus_allowed_list:\s*(\S+)", r.stdout)
        mem_b = int(mem.group(1)) if mem else None
        ncpu = int(cpus.group(1)) if cpus else None
        cpu_id = bound.group(1) if bound else None
        in_share = cpu_id in allowed[w].split(",")
        ok &= r.returncode == 0 and mem_b == 200 * 2**20 and ncpu == 1 and in_share
        parts.append(f"{w}: memory.max={mem_b}, CPUs={ncpu} (cpu {cpu_id}, share {allowed[w]})")
        data[w] = {"memory_max": mem_b, "cpus": ncpu, "cpu": cpu_id, "share": allowed[w]}
    return Check(f"{label}limits_on_process", ok,
                 "; ".join(parts) + f" — want memory.max={200 * 2**20}, 1 CPU inside the share",
                 data)


def check_oom(plan: emu.Plan, launcher: str = "", label: str = "") -> Check:
    r = _as_user(plan, f"srun -N1 -n1 -c1 --mem=100M -t 1 {launcher}"
                       "python3 -c 'x = b\"x\" * (300 << 20); print(len(x))'")
    text = (r.stdout + r.stderr).lower()
    ok = r.returncode != 0 and ("oom" in text or "out of memory" in text or "out_of_memory" in text)
    return Check(f"{label}memory_enforced", ok,
                 f"300 MiB allocation under --mem=100M: rc={r.returncode}"
                 + (" (OOM-killed)" if ok else f"; output: {text.strip()[-200:]}"))


def check_exit_codes(plan: emu.Plan, launcher: str = "", label: str = "") -> Check:
    r1 = _as_user(plan, f"srun -N1 -t 1 {launcher}bash -c 'exit 3'")
    r2 = _as_user(plan, "sbatch --parsable --wait -N1 -t 1 -o /dev/null "
                        f"--wrap '{launcher}bash -c \"exit 4\"'")
    job = r2.stdout.strip().split(";")[0]
    exit_field = _job_field(plan, job, "ExitCode") if job else None
    ok = r1.returncode == 3 and r2.returncode == 4 and exit_field == "4:0"
    return Check(f"{label}exit_codes", ok,
                 f"srun rc={r1.returncode} (want 3); sbatch --wait rc={r2.returncode} "
                 f"(want 4); job {job} ExitCode={exit_field} (want 4:0)")


def check_timeout(plan: emu.Plan) -> Check:
    t0 = time.monotonic()
    r = _as_user(plan, "sbatch --parsable --wait -N1 -t 0:15 -o /dev/null --wrap 'sleep 600'",
                 timeout=300)
    elapsed = time.monotonic() - t0
    job = r.stdout.strip().split(";")[0]
    state = _wait_terminal(plan, job) if job else None
    left = _user_procs(plan)
    ok = state == "TIMEOUT" and not left
    return Check("timeout_enforced", ok,
                 f"job {job} state={state} after {elapsed:.0f}s (limit 15s, rounded up to "
                 f"Slurm's 1-minute granularity); leftover processes: {left or 'none'}",
                 {"elapsed_s": round(elapsed, 1)})


CANCEL_STEP = (
    # Each task ignores SIGTERM, forks a child that also ignores it, and starts a process
    # in a new session (as a daemon would) to check that cgroup tracking catches escapees.
    "trap \"\" TERM; (trap \"\" TERM; sleep 600) & setsid sleep 600 & sleep 600"
)


def _root_container_procs(nodes: list[str]) -> dict[str, list[str]]:
    """Root-owned container runtime processes; a rootless launch must create none."""
    found = {}
    for n in nodes:
        r = emu.exec_(n, "pgrep", "-u", "root", "-af", "apptainer|starter|squashfuse|conmon|crun",
                      check=False)
        lines = [l for l in r.stdout.splitlines() if "pgrep" not in l]
        if lines:
            found[n] = lines
    return found


def check_cancel_cleanup(plan: emu.Plan, launcher: str = "", label: str = "") -> Check:
    name = f"{label}cancel_cleanup"
    n = min(2, len(plan.hosts) - 1)
    script = f"#!/bin/bash\nsrun --ntasks-per-node=1 {launcher}bash -c '{CANCEL_STEP}'\n"
    r = _as_user(plan, f"sbatch --parsable -N{n} -t 5 -o /dev/null <<'EOF'\n{script}EOF")
    job = r.stdout.strip().split(";")[0]
    if r.returncode != 0 or not job:
        return Check(name, False, f"submit failed: {r.stderr.strip()}")

    deadline = time.monotonic() + 30
    nodes: list[str] = []
    while time.monotonic() < deadline:
        procs = _user_procs(plan)
        if len(procs) >= n and all(sum("sleep" in p for p in v) >= 3 for v in procs.values()):
            nodes = sorted(procs)
            break
        time.sleep(1)
    if not nodes:
        _as_user(plan, f"scancel {job}")
        return Check(name, False, f"job {job} never had all processes running")

    root_procs = _root_container_procs(nodes) if launcher else {}
    t0 = time.monotonic()
    _as_user(plan, f"scancel {job}")
    left = _user_procs(plan)
    while left and time.monotonic() - t0 < KILL_WAIT_S + 30:
        time.sleep(1)
        left = _user_procs(plan)
    elapsed = time.monotonic() - t0
    state = _wait_terminal(plan, job)
    cgroups = _job_cgroups(plan, job, nodes)
    ok = not left and state == "CANCELLED" and not cgroups and not root_procs
    detail = (f"job {job} on {','.join(nodes)}: state={state}, "
              f"{'all processes gone' if not left else 'LEFTOVER ' + str(left)} "
              f"after {elapsed:.1f}s (KillWait={KILL_WAIT_S}s; tasks ignored SIGTERM); "
              f"job cgroups left: {cgroups or 'none'}")
    if launcher:
        detail += f"; root-owned runtime processes while running: {root_procs or 'none'}"
    return Check(name, ok, detail,
                 {"cleanup_s": round(elapsed, 1), "root_container_procs": root_procs})


def _wait_terminal(plan: emu.Plan, job: str, timeout_s: float = 30) -> str | None:
    """Job state once it leaves PENDING/RUNNING/COMPLETING (epilog finished)."""
    deadline = time.monotonic() + timeout_s
    state = None
    while time.monotonic() < deadline:
        state = _job_field(plan, job, "JobState")
        if state not in ("PENDING", "RUNNING", "COMPLETING", "CONFIGURING"):
            return state
        time.sleep(1)
    return state


def _job_cgroups(plan: emu.Plan, job: str, nodes: list[str]) -> list[str]:
    left = []
    for n in nodes:
        r = emu.exec_(n, "bash", "-c",
                      f"ls -d /sys/fs/cgroup/system.slice/*_slurmstepd.scope/job_{job} 2>/dev/null",
                      check=False)
        if r.stdout.strip():
            left.append(n)
    return left


def verify(plan: emu.Plan, skip_slow: bool = False, log=print) -> list[Check]:
    n_workers = len(plan.hosts) - 1
    steps = [lambda: check_nodes(plan)]
    steps += [lambda n=n: check_allocation(plan, n) for n in (1, 2, 4, 8) if n <= n_workers]
    cores = int(next(iter(emu.running_nodes().values()))["labels"]
                ["daisychain.worker_cores"])
    host_cpus = parse_slurmd_c(emu.exec_(plan.hosts[1], "slurmd", "-C").stdout)["CPUs"]
    steps += [lambda: check_limits(plan, cores, host_cpus), lambda: check_oom(plan),
              lambda: check_exit_codes(plan), lambda: check_cancel_cleanup(plan)]
    if not skip_slow:
        steps.append(lambda: check_timeout(plan))
    results = []
    for step in steps:
        c = step()
        results.append(c)
        log(f"{'OK  ' if c.ok else 'FAIL'}  {c.name:18s} {c.detail}")
    return results
