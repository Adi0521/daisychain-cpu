# ---- exporters -----------------------------------------------------------------------------


def exporter_command(plan: emu.Plan, node: str) -> list[str]:
    if node in plan.switches:
        return ["prometheus-node-exporter",
                f"--web.listen-address={plan.switch_addresses[node]}:{NODE_PORT}",
                "--collector.disable-defaults", "--collector.netdev", "--collector.qdisc"]
    return ["prometheus-node-exporter", f"--web.listen-address={plan.addresses[node]}:{NODE_PORT}",
            f"--collector.textfile.directory={METRICS_DIR}", "--collector.qdisc"]


CGROUP_LOOP = f"""
# Emulator only: this container's own CPU and memory from its cgroup v2 root.
f={METRICS_DIR}/emu-cgroup.prom
while true; do
  usec=$(awk '/^usage_usec/ {{print $2}}' /sys/fs/cgroup/cpu.stat)
  mem=$(cat /sys/fs/cgroup/memory.current)
  printf '# TYPE daisychain_emu_cgroup_cpu_seconds_total counter\\ndaisychain_emu_cgroup_cpu_seconds_total %s\\n# TYPE daisychain_emu_cgroup_memory_bytes gauge\\ndaisychain_emu_cgroup_memory_bytes %s\\n' \\
    "$(awk -v u="$usec" 'BEGIN {{printf "%.6f", u / 1e6}}')" "$mem" > "$f.tmp" && mv "$f.tmp" "$f"
  sleep {SCRAPE_S}
done
"""


def start_exporters(plan: emu.Plan) -> None:
    for node in plan.nodes:
        emu.exec_(node, "pkill", "-f", "prometheus-node-exporter|daisychain-slurm-exporter|emu-cgroup",
                  check=False)
        emu._docker("exec", "-d", emu.container(node), *exporter_command(plan, node))
        if node in plan.hosts:
            emu._docker("exec", "-d", emu.container(node), "bash", "-c",
                        "exec -a emu-cgroup bash -c " + shlex.quote(CGROUP_LOOP))
    c0 = plan.hosts[0]
    emu._docker("exec", "-d", emu.container(c0), "daisychain-slurm-exporter", "--listen",
                f"{plan.addresses[c0]}:{SLURM_PORT}")


