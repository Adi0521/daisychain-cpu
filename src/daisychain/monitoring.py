"""Monitoring on the emulated cluster: exporters, Prometheus, Grafana (PRD F8, §9).

Layout (mirrors the PRD: Prometheus and Grafana run on the controller):

* node_exporter on C0 and every worker, listening on its data address. CPU, RAM, swap,
  NIC bytes/errors, NFS client/server counters, and textfile metrics (model-load times
  written by daisychain-stage).
* node_exporter on every switch, on an in-band management address on its bridge, with
  only the netdev and qdisc collectors: per-port byte/drop counters, as a managed switch
  would expose over SNMP.
* daisychain-slurm-exporter on C0: Slurm node and job states.
* Prometheus and Grafana from their official images, sharing C0's network namespace, so
  they *are* on C0 as far as the network is concerned. Every scrape crosses the emulated
  fabric, so monitoring traffic shares the chain's links as it will on hardware.
* A relay container (dc-mgmt) connected to C0 by a separate, unshaped management link
  publishes Grafana and Prometheus on 127.0.0.1 of the Mac. Browser traffic never
  touches the data fabric.

Emulation caveat: node_exporter reads /proc, which in a container shows the whole Docker
VM, so CPU, memory, swap and disk panels are identical for every node. Network and NFS
counters are per network namespace and therefore per node. An emulator-only textfile
loop exports each container's own cgroup CPU and memory (daisychain_emu_cgroup_*).
"""

