def aux_containers() -> list[str]:
    out = emu._docker("ps", "-a", "--filter", f"label={AUX_LABEL}", "--format", "{{.Names}}").stdout
    return out.split()


def stop() -> None:
    names = aux_containers()
    if names:
        emu._docker("rm", "-f", *names)


def _create_with_files(name: str, image: str, run_args: list[str], cmd: list[str],
                       files: dict[str, str]) -> None:
    """Create a container, copy config files in, then start it.

    `docker cp` cannot create missing parent directories, so files are grouped by their
    directory: an existing directory gets files copied into it; a missing one is copied
    in whole (keys are absolute paths in the container).
    """
    emu._docker("create", "--name", name, "--label", f"{AUX_LABEL}=monitoring", *run_args,
                image, *cmd)
    by_dir: dict[str, dict[str, str]] = {}
    for dest, content in files.items():
        d, _, base = dest.rpartition("/")
        by_dir.setdefault(d, {})[base] = content
    with tempfile.TemporaryDirectory() as tmp:
        for i, (d, entries) in enumerate(by_dir.items()):
            src = Path(tmp) / f"d{i}"
            src.mkdir()
            for base, content in entries.items():
                (src / base).write_text(content)
                (src / base).chmod(0o644)
            src.chmod(0o755)
            exists = emu._docker("run", "--rm", "--entrypoint", "test", image, "-d", d,
                                 check=False).returncode == 0
            if exists:
                for base in entries:
                    emu._docker("cp", str(src / base), f"{name}:{d}/{base}")
            else:
                emu._docker("cp", str(src), f"{name}:{d}")
    emu._docker("start", name)


RELAY_WIRING = """set -euo pipefail
mkdir -p /var/run/netns
ln -sfn /proc/{c0_pid}/ns/net /var/run/netns/mgmt-c0
ln -sfn /proc/{relay_pid}/ns/net /var/run/netns/mgmt-relay
ip link add dcmg0 type veth peer name dcmg1
ip link set dcmg0 netns mgmt-c0
ip -n mgmt-c0 link set dcmg0 name mgmt0
ip -n mgmt-c0 addr add {c0}/{prefix} dev mgmt0
ip -n mgmt-c0 link set mgmt0 up
ip link set dcmg1 netns mgmt-relay
ip -n mgmt-relay link set dcmg1 name mgmt0
ip -n mgmt-relay addr add {relay}/{prefix} dev mgmt0
ip -n mgmt-relay link set mgmt0 up
rm -f /var/run/netns/mgmt-c0 /var/run/netns/mgmt-relay
"""


def start_relay(plan: emu.Plan, ports: dict[str, int]) -> None:
    """Management link: Mac 127.0.0.1:<port> → relay → C0 over an unshaped veth."""
    emu._docker("run", "-d", "--name", RELAY, "--label", f"{AUX_LABEL}=monitoring",
                "--label", f"daisychain.ui_ports={json.dumps(ports)}",
                *[a for svc, p in ports.items()
                  for a in ("-p", f"127.0.0.1:{p}:{DEFAULT_PORTS[svc]}")],
                emu.IMAGE, "sleep", "infinity")
    pid = lambda n: emu._docker("inspect", "-f", "{{.State.Pid}}", n).stdout.strip()
    emu._docker("run", "--rm", "-i", "--privileged", "--pid=host", "--net=host", emu.IMAGE,
                "bash", "-s", input=RELAY_WIRING.format(
                    c0_pid=pid(emu.container(plan.hosts[0])), relay_pid=pid(RELAY),
                    c0=MGMT_C0, relay=MGMT_RELAY, prefix=MGMT_PREFIX))
    for port in DEFAULT_PORTS.values():
        emu._docker("exec", "-d", RELAY, "socat", f"TCP-LISTEN:{port},fork,reuseaddr",
                    f"TCP:{MGMT_C0}:{port}")


def ui_ports() -> dict[str, int]:
    r = emu._docker("inspect", "-f", '{{index .Config.Labels "daisychain.ui_ports"}}', RELAY,
                    check=False)
    try:
        return json.loads(r.stdout.strip())
    except ValueError:
        raise emu.EmuError("monitoring is not running (no dc-mgmt relay); "
                           "start the cluster without --no-monitoring")


def start(plan: emu.Plan, ports: dict[str, int] | None = None, log=print) -> None:
    ports = {**DEFAULT_PORTS, **(ports or {})}
    stop()
    start_exporters(plan)
    files = render(plan)
    c0_net = ["--network", f"container:{emu.container(plan.hosts[0])}"]
    _create_with_files(
        PROM, PROM_IMAGE, c0_net,
        ["--config.file=/etc/prometheus/prometheus.yml", "--storage.tsdb.path=/prometheus",
         "--storage.tsdb.retention.time=7d", "--web.listen-address=0.0.0.0:9090"],
        {"/etc/prometheus/prometheus.yml": files["prometheus/prometheus.yml"],
         "/etc/prometheus/rules.yml": files["prometheus/rules.yml"]})
    env = {
        "GF_AUTH_ANONYMOUS_ENABLED": "true", "GF_AUTH_ANONYMOUS_ORG_ROLE": "Viewer",
        "GF_SECURITY_ADMIN_PASSWORD": "daisychain",
        "GF_DASHBOARDS_DEFAULT_HOME_DASHBOARD_PATH": f"{GRAFANA_DASHBOARDS}/cluster.json",
        # C0 has no internet: don't let Grafana try.
        "GF_ANALYTICS_REPORTING_ENABLED": "false", "GF_ANALYTICS_CHECK_FOR_UPDATES": "false",
        "GF_ANALYTICS_CHECK_FOR_PLUGIN_UPDATES": "false", "GF_PLUGINS_PREINSTALL_DISABLED": "true",
        "GF_NEWS_NEWS_FEED_ENABLED": "false",
    }
    _create_with_files(
        GRAFANA, GRAFANA_IMAGE, c0_net + [a for k, v in env.items() for a in ("-e", f"{k}={v}")], [],
        {"/etc/grafana/provisioning/datasources/prometheus.yml":
             files["grafana/provisioning/datasources/prometheus.yml"],
         "/etc/grafana/provisioning/dashboards/daisychain.yml":
             files["grafana/provisioning/dashboards/daisychain.yml"],
         f"{GRAFANA_DASHBOARDS}/cluster.json": files["grafana/dashboards/cluster.json"]})
    start_relay(plan, ports)
    _wait_http(f"http://127.0.0.1:{ports['prometheus']}/-/ready", 60)
    _wait_http(f"http://127.0.0.1:{ports['grafana']}/api/health", 90)
    log(f"monitoring: Grafana http://127.0.0.1:{ports['grafana']}  "
        f"Prometheus http://127.0.0.1:{ports['prometheus']}  (scrape every {SCRAPE_S}s)")


def _wait_http(url: str, timeout_s: float) -> None:
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        try:
            with urllib.request.urlopen(url, timeout=3) as r:
                if r.status == 200:
                    return
        except Exception as e:  # noqa: BLE001 - any failure means "not ready yet"
            last = e
        time.sleep(1)
    raise emu.EmuError(f"{url} not ready after {timeout_s:.0f}s: {last}")


# ---- querying ------------------------------------------------------------------------------


def _get(path: str, params: dict | None = None, service: str = "prometheus", timeout: float = 10):
    port = ui_ports()[service]
    url = f"http://127.0.0.1:{port}{path}"
    if params:
        url += "?" + urllib.parse.urlencode(params)
    with urllib.request.urlopen(url, timeout=timeout) as r:
        return json.loads(r.read())


def query(expr: str, at: float | None = None) -> list[dict]:
    params = {"query": expr}
    if at is not None:
        params["time"] = f"{at:.3f}"
    res = _get("/api/v1/query", params)
    if res.get("status") != "success":
        raise emu.EmuError(f"query failed: {expr}: {res}")
    return res["data"]["result"]


def by_node(expr: str) -> dict[str, float]:
    return {r["metric"].get("node", "?"): float(r["value"][1]) for r in query(expr)}


def query_range(expr: str, start: float, end: float, step: float = SCRAPE_S) -> list[dict]:
    res = _get("/api/v1/query_range", {"query": expr, "start": f"{start:.3f}",
                                       "end": f"{end:.3f}", "step": f"{step:g}"}, timeout=60)
    return res["data"]["result"]


def _wait_for(pred, timeout_s: float, poll_s: float = 1):
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        v = pred()
        if v:
            return v
        time.sleep(poll_s)
    return None


# ---- acceptance checks ---------------------------------------------------------------------


def _wait_fresh_scrape() -> None:
    """Sleep past one full scrape interval so every target has a sample newer than now."""
    time.sleep(SCRAPE_S + 1.5)


def check_targets(plan: emu.Plan) -> Check:
    expected = {(job, c["labels"]["node"]) for job, cfgs in targets(plan).items() for c in cfgs}
    # Right after start-up, targets are "unknown" until their first scrape: allow two rounds.
    deadline = time.monotonic() + 2 * SCRAPE_S + 2
    while True:
        res = _get("/api/v1/targets")["data"]["activeTargets"]
        up = {(t["labels"]["job"], t["labels"].get("node")) for t in res if t["health"] == "up"}
        if expected <= up or time.monotonic() > deadline:
            break
        time.sleep(1)
    intervals = {t["scrapeInterval"] for t in res}
    missing = sorted(expected - up)
    ok = not missing and intervals == {f"{SCRAPE_S}s"}
    return Check("targets_up", ok,
                 f"{len(up & expected)}/{len(expected)} targets up "
                 f"({len(plan.hosts)} hosts, {len(plan.switches)} switches, Slurm, Prometheus); "
                 f"scrape interval {', '.join(sorted(intervals))}"
                 + (f"; DOWN: {missing}" if missing else ""))


HOST_SERIES = {
    "cpu": 'count by (node) (node_cpu_seconds_total{job="node",mode="idle"})',
    "memory": 'node_memory_MemAvailable_bytes{job="node"}',
    "swap": 'node_memory_SwapTotal_bytes{job="node"}',
    "disk": 'count by (node) (node_disk_read_bytes_total{job="node"})',
    "nic": 'node_network_transmit_bytes_total{job="node",device="eth0"}',
    "nic_errors": 'node_network_receive_errs_total{job="node",device="eth0"}',
    "container_cpu": "daisychain_emu_cgroup_cpu_seconds_total",
}


def check_host_metrics(plan: emu.Plan) -> Check:
    missing = {}
    for name, expr in HOST_SERIES.items():
        have = set(by_node(expr))
        lack = [h for h in plan.hosts if h not in have]
        if lack:
            missing[name] = lack
    workers = plan.hosts[1:]
    nfs_client = set(by_node('node_nfs_requests_total{method="Read"}'))
    if set(workers) - nfs_client:
        missing["nfs_client"] = sorted(set(workers) - nfs_client)
    if plan.hosts[0] not in by_node("sum by (node) (node_nfsd_server_rpcs_total)"):
        missing["nfs_server"] = [plan.hosts[0]]
    return Check("host_metrics", not missing,
                 f"CPU, memory, swap, disk, NIC bytes/errors and container CPU for all "
                 f"{len(plan.hosts)} hosts; NFS client counters on {len(workers)} workers; "
                 f"nfsd counters on {plan.hosts[0]}"
                 if not missing else f"missing series: {missing}")


def check_switch_counters(plan: emu.Plan, mbytes: int = 50) -> Check:
    """Switch port counters seen by Prometheus match the shaper's own byte counters."""
    from . import storage

    a, b = plan.hosts[1], plan.hosts[-1]
    hops = [(s, d) for s, d in plan.topo.route(a, b) if s in plan.switches]
    expr = lambda s, d: (f'node_qdisc_bytes_total{{job="switch",kind="tbf",node="{s}",'
                         f'device="p-{d}"}}')
    def prom():
        return {h: float(query(expr(*h))[0]["value"][1]) for h in hops}
    _wait_fresh_scrape()
    p0, t0 = prom(), storage.link_counters(plan)
    emu.exec_(b, "iperf3", "-s", "-D", "-1", "-p", "5310")
    time.sleep(0.5)
    emu.exec_(a, "iperf3", "-c", plan.addresses[b], "-p", "5310", "-n", f"{mbytes}M")
    t1 = storage.link_counters(plan)
    _wait_fresh_scrape()
    p1 = prom()
    rows, ok = [], True
    for h in hops:
        dp, dt = p1[h] - p0[h], t1[h] - t0[h]
        good = dt > mbytes * 1e6 and abs(dp - dt) <= 0.02 * dt
        ok &= good
        rows.append(f"{h[0]}->{h[1]} {dp / 1e6:.1f}/{dt / 1e6:.1f} MB")
    return Check("switch_port_counters", ok,
                 f"{a}->{b} {mbytes} MB: Prometheus/shaper bytes per hop: " + ", ".join(rows))


def check_slurm_metrics(plan: emu.Plan) -> Check:
    workers = plan.hosts[1:3]
    r = slurm._as_user(plan, f"sbatch --parsable -N{len(workers)} -w {','.join(workers)} -t 2 "
                             "-o /dev/null --wrap 'sleep 60'")
    job = r.stdout.strip().split(";")[0]
    t0 = time.monotonic()
    running = _wait_for(lambda: by_node('daisychain_slurm_jobs{state="RUNNING"} >= 1'), 20, 0.5)
    seen_running = time.monotonic() - t0
    alloc = by_node('daisychain_slurm_cpus{state="alloc"}')
    cancelled0 = sum(by_node('daisychain_slurm_jobs{state="CANCELLED"}').values())
    slurm._as_user(plan, f"scancel {job}")
    t1 = time.monotonic()
    cancelled = _wait_for(lambda: sum(by_node('daisychain_slurm_jobs{state="CANCELLED"}').values())
                          > cancelled0, 20, 0.5)
    seen_cancel = time.monotonic() - t1
    ok = bool(running) and bool(cancelled) and sum(alloc.values()) > 0
    return Check("slurm_job_state", ok,
                 f"job {job}: RUNNING visible after {seen_running:.1f}s, allocated CPUs "
                 f"{int(sum(alloc.values()))}, CANCELLED visible {seen_cancel:.1f}s after scancel")


def check_staging_metrics(plan: emu.Plan) -> Check:
    """Model-load time reaches Prometheus from every worker (textfile collector)."""
    from . import storage

    art = "models/monitor-probe"
    storage.publish_synthetic(plan, "monitor-probe", 16, files=2, replace=True)
    storage.clear_local(plan, art)
    res = storage.stage(plan, art)
    _wait_fresh_scrape()
    secs = by_node(f'daisychain_stage_seconds{{artifact="{art}"}}')
    good = by_node(f'daisychain_stage_success{{artifact="{art}"}} == 1')
    storage.clear_local(plan, art)
    storage.unpublish(plan, art)
    workers = plan.hosts[1:]
    ok = all(r["status"] == "ok" for r in res) and set(secs) == set(workers) == set(good)
    detail = (f"16 MiB staged on {len(workers)} workers; daisychain_stage_seconds from "
              f"{len(secs)} workers ({min(secs.values()):.2f}–{max(secs.values()):.2f} s)"
              if secs else f"no staging metrics; staging results {res}")
    return Check("staging_metrics", ok, detail)


def check_missing_worker(plan: emu.Plan, bound_s: float = 30) -> Check:
    """PRD §9: missing worker telemetry is visible within 30 s (worker frozen, not removed)."""
    w = plan.hosts[-1]
    expr = f'up{{job="node",node="{w}"}} == 0'
    alert = f'ALERTS{{alertname="TelemetryMissing",node="{w}",alertstate="firing"}}'
    emu._docker("pause", emu.container(w))
    t0 = time.monotonic()
    try:
        down = _wait_for(lambda: query(expr), bound_s + 30, 0.5)
        detect = time.monotonic() - t0
        firing = _wait_for(lambda: query(alert), 20, 0.5)
        alert_s = time.monotonic() - t0
    finally:
        emu._docker("unpause", emu.container(w))
    t1 = time.monotonic()
    back = _wait_for(lambda: query(f'up{{job="node",node="{w}"}} == 1'), 60, 0.5)
    recover = time.monotonic() - t1
    ok = bool(down) and detect <= bound_s and bool(firing) and bool(back)
    return Check("missing_worker_detected", ok,
                 f"{w} frozen (docker pause): up=0 after {detect:.1f}s (bound {bound_s:.0f}s), "
                 f"TelemetryMissing firing after {alert_s:.1f}s; back up {recover:.1f}s after "
                 "unfreezing", {"detect_s": round(detect, 1), "alert_s": round(alert_s, 1)})


REQUEST_METRICS = ("daisychain_router_queue_depth", "daisychain_requests_in_flight",
                   "daisychain_requests_total", "daisychain_request_duration_seconds_bucket")


def check_dashboard(plan: emu.Plan) -> Check:
    """Provisioned dashboard loads in Grafana; every panel query runs; all have data except
    the request panels, whose metrics come from the router (not built yet), and the
    inter-switch panel on a topology without inter-switch links."""
    port = ui_ports()["grafana"]
    with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/dashboards/uid/{DASHBOARD_UID}",
                                timeout=10) as r:
        dash = json.loads(r.read())["dashboard"]
    with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/datasources/uid/prometheus/health",
                                timeout=10) as r:
        ds_ok = json.loads(r.read()).get("status") == "OK"
    empty, errors, n = [], [], 0
    for p in dash["panels"]:
        for t in p.get("targets", []):
            n += 1
            try:
                no_isl = p["title"] == "Inter-switch link utilisation" and not plan.topo.switch_links
                if not query(t["expr"]) and not no_isl and not any(m in t["expr"] for m in REQUEST_METRICS):
                    empty.append(p["title"])
            except Exception as e:  # noqa: BLE001
                errors.append(f"{p['title']}: {e}")
    ok = ds_ok and not empty and not errors
    return Check("dashboard", ok,
                 f"'{dash['title']}' provisioned with {len(dash['panels'])} panels; datasource "
                 f"{'OK' if ds_ok else 'FAILING'}; {n} queries, "
                 f"{'all with data except the router request panels' if not empty else 'EMPTY: ' + ', '.join(sorted(set(empty)))}"
                 + (f"; errors: {errors}" if errors else ""))


def _iface_bytes(node: str, dev: str, direction: str) -> int:
    return int(emu.exec_(node, "cat", f"/sys/class/net/{dev}/statistics/{direction}_bytes").stdout)


def check_management_path(plan: emu.Plan, fetches: int = 20) -> Check:
    """Browser traffic uses the management link, not the data fabric."""
    c0 = plan.hosts[0]
    port = ui_ports()["grafana"]
    e0, m0 = _iface_bytes(c0, "eth0", "tx"), _iface_bytes(c0, "mgmt0", "tx")
    total = 0
    for _ in range(fetches):
        try:
            with urllib.request.urlopen(f"http://127.0.0.1:{port}/api/dashboards/uid/{DASHBOARD_UID}",
                                        timeout=10) as r:
                total += len(r.read())
        except Exception:  # noqa: BLE001
            pass
    e1, m1 = _iface_bytes(c0, "eth0", "tx"), _iface_bytes(c0, "mgmt0", "tx")
    ok = (m1 - m0) >= total > 0 and (e1 - e0) < total / 2
    return Check("management_path", ok,
                 f"{fetches} dashboard fetches ({total / 1e3:.0f} kB): C0 mgmt0 sent "
                 f"{(m1 - m0) / 1e3:.0f} kB, data eth0 sent {(e1 - e0) / 1e3:.0f} kB "
                 "(scrape requests only)")


def verify(plan: emu.Plan, log=print) -> list[Check]:
    steps = [check_targets, check_host_metrics, check_switch_counters, check_slurm_metrics,
             check_staging_metrics, check_missing_worker, check_dashboard, check_management_path]
    results = []
    for step in steps:
        c = step(plan)
        results.append(c)
        log(f"{'OK  ' if c.ok else 'FAIL'}  {c.name:24s} {c.detail}")
        if c.name == "targets_up" and not c.ok:
            break
    return results


# ---- overhead (PRD §9: measured against a disabled-monitoring run) -------------------------


def _cpu_seconds(plan: emu.Plan) -> dict[str, float]:
    """Cumulative CPU seconds of the monitoring stack: Prometheus, Grafana, all exporters."""
    out = {}
    for name in (PROM, GRAFANA):
        r = emu._docker("exec", name, "cat", "/sys/fs/cgroup/cpu.stat", check=False)
        usec = next((int(l.split()[1]) for l in r.stdout.splitlines() if l.startswith("usage_usec")), 0)
        out[name] = usec / 1e6
    total = 0.0
    for node in plan.nodes:
        r = emu.exec_(node, "bash", "-c",
                      "for p in $(pgrep -f 'prometheus-node-exporter|daisychain-slurm-exporter|emu-cgroup'); do "
                      "awk '{print $14 + $15 + $16 + $17}' /proc/$p/stat 2>/dev/null; done", check=False)
        total += sum(float(x) for x in r.stdout.split()) / 100  # clock ticks
    out["exporters"] = total
    return out


def _set_scraping(on: bool) -> None:
    emu._docker("unpause" if on else "pause", PROM, check=False)


def overhead(plan: emu.Plan, idle_s: int = 30, repeats: int = 3, log=print) -> dict:
    from . import mpi, storage

    report: dict = {"idle_s": idle_s, "repeats": repeats, "idle": {}, "workloads": []}
    # 1. Idle fabric traffic and CPU with scraping on vs off.
    c0 = plan.hosts[0]
    for state in ("on", "off"):
        _set_scraping(state == "on")
        time.sleep(2)
        l0, cpu0 = storage.link_counters(plan), _cpu_seconds(plan)
        rx0, tx0 = _iface_bytes(c0, "eth0", "rx"), _iface_bytes(c0, "eth0", "tx")
        time.sleep(idle_s)
        l1, cpu1 = storage.link_counters(plan), _cpu_seconds(plan)
        rx1, tx1 = _iface_bytes(c0, "eth0", "rx"), _iface_bytes(c0, "eth0", "tx")
        report["idle"][state] = r = {
            "link_bps": {f"{s}->{d}": round((l1[(s, d)] - l0[(s, d)]) * 8 / idle_s, 1) for s, d in l1},
            "c0_rx_bps": round((rx1 - rx0) * 8 / idle_s, 1),
            "c0_tx_bps": round((tx1 - tx0) * 8 / idle_s, 1),
            "cpu_cores": {k: round((cpu1[k] - cpu0[k]) / idle_s, 4) for k in cpu1},
        }
        log(f"idle, scraping {state}: C0 NIC rx {r['c0_rx_bps'] / 1e3:.1f} kb/s, "
            f"tx {r['c0_tx_bps'] / 1e3:.1f} kb/s; monitoring CPU "
            f"{sum(r['cpu_cores'].values()):.3f} cores")
    _set_scraping(True)

    # 2. Chain-sensitive workloads, alternating on/off so drift affects both equally.
    mpi.ensure_staged(plan, log=log)
    ws = plan.hosts[1:]
    workloads = [("alltoall 1 MiB x 8 ranks", ws, "alltoall --sizes 1048576", "us_p50", "ms"),
                 ("cross pairs bw 4 MiB", ws, "bw --sizes 4194304", "total_mbps", "Mb/s")]
    for title, nodes, args, key, unit in workloads:
        vals: dict[str, list[float]] = {"on": [], "off": []}
        for _ in range(repeats):
            for state in ("on", "off"):
                _set_scraping(state == "on")
                rows, r = mpi.run(plan, nodes, args)
                if r.returncode != 0 or not rows:
                    _set_scraping(True)
                    raise emu.EmuError(f"{title} failed: {r.stderr.strip()[-300:]}")
                v = rows[0][key] / (1000 if unit == "ms" else 1)
                vals[state].append(v)
        _set_scraping(True)
        on, off = (sum(vals[s]) / len(vals[s]) for s in ("on", "off"))
        change = (on - off) / off
        report["workloads"].append({"workload": title, "unit": unit, "on": vals["on"],
                                    "off": vals["off"], "mean_on": round(on, 3),
                                    "mean_off": round(off, 3), "change": round(change, 4)})
        log(f"{title}: monitoring on {on:.2f} {unit}, off {off:.2f} {unit} ({change:+.1%})")
    return report


