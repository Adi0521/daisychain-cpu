@dataclass
class _Layout:
    panels: list = field(default_factory=list)
    y: int = 0
    x: int = 0
    next_id: int = 1

    def row(self, title: str) -> None:
        if self.x:
            self.y, self.x = self.y + 8, 0
        self.panels.append({"type": "row", "title": title, "id": self.next_id,
                            "gridPos": {"h": 1, "w": 24, "x": 0, "y": self.y}, "collapsed": False})
        self.next_id += 1
        self.y += 1

    def panel(self, title: str, targets_: list[tuple[str, str]], unit: str = "short",
              kind: str = "timeseries", w: int = 8, desc: str = "", extra: dict | None = None):
        if self.x + w > 24:
            self.y, self.x = self.y + 8, 0
        p = {"type": kind, "title": title, "id": self.next_id, "datasource": DS,
             "description": desc,
             "gridPos": {"h": 8, "w": w, "x": self.x, "y": self.y},
             "targets": [{"datasource": DS, "expr": e, "legendFormat": l, "refId": chr(65 + i)}
                         for i, (e, l) in enumerate(targets_)],
             "fieldConfig": {"defaults": {"unit": unit}, "overrides": []},
             "options": {}}
        if extra:
            for k, v in extra.items():
                if isinstance(v, dict) and isinstance(p.get(k), dict):
                    p[k].update(v)
                else:
                    p[k] = v
        self.panels.append(p)
        self.next_id += 1
        self.x += w


